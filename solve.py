#!/usr/bin/env python3
"""
[던전의 비밀: 마왕의 보물상자] 풀이 스크립트 (Solve Script)

- Ghidra/IDA 등에서 확인한 ENCRYPTED_KEY 바이트 배열과 XOR_KEY(0x5A)를 이용하여 원본 플래그를 복구합니다.
"""

ENCRYPTED_KEY = [
    0x1c, 0x16, 0x1b, 0x1d, 0x21, 0x3e, 0x2f, 0x34, 0x3d, 0x3f, 0x35, 0x34,
    0x05, 0x2e, 0x28, 0x3f, 0x3b, 0x29, 0x2f, 0x28, 0x3f, 0x05, 0x2f, 0x34,
    0x36, 0x35, 0x39, 0x31, 0x3f, 0x3e, 0x7b, 0x27
]

XOR_KEY = 0x5A

def solve():
    flag = ''.join(chr(b ^ XOR_KEY) for b in ENCRYPTED_KEY)
    print("=" * 45)
    print(f"🎉 복호화된 보물상자 주문 (FLAG): {flag}")
    print("=" * 45)

if __name__ == "__main__":
    solve()
